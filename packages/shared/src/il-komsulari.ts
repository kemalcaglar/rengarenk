/** İl adına göre komşu il adları (`ILLER` yazımıyla) */
export function ilKomsulari(il: string): readonly string[] {
  const p = ILLER.find((x) => x.ad === il)?.plaka;
  const k = p ? KOMSU[p] : undefined;
  return k ? k.map((x) => ILLER.find((i) => i.plaka === x)?.ad).filter((x): x is string => Boolean(x)) : [];
}

